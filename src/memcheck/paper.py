"""Paper source validation and build.

Where a LaTeX engine is unavailable — as in the environment this artifact was developed in —
validation stands in for compilation. It checks the things a failed compile would have caught,
plus the things a *successful* compile would not have caught: undefined citations, missing
generated inputs, and prose that presents an unsupported claim as a finding.
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

INPUT_PATTERN = re.compile(r"\\(?:input|include)\{([^}]+)\}")
GRAPHICS_PATTERN = re.compile(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}")
CITE_PATTERN = re.compile(r"\\cite[tp]?\*?(?:\[[^\]]*\])*\{([^}]+)\}")
BIB_ENTRY_PATTERN = re.compile(r"@\w+\s*\{\s*([^,\s]+)\s*,")
BEGIN_PATTERN = re.compile(r"\\begin\{([^}]+)\}")
END_PATTERN = re.compile(r"\\end\{([^}]+)\}")
LABEL_PATTERN = re.compile(r"\\label\{([^}]+)\}")
REF_PATTERN = re.compile(r"\\(?:ref|autoref|Cref|cref)\{([^}]+)\}")
#: 2026-11-13T00:00:00Z, the submission deadline.
ANONYMOUS_SOURCE_DATE_EPOCH = "1794528000"

PENDING_PATTERN = re.compile(r"\[RESULT PENDING:[^\]]*\]")
#: Claim macros are \memcheck followed by upper-case letters only (memcheck.reporting.claims
#: spells digits as letters), which distinguishes them from flags such as \memcheckanonymous.
MACRO_USE_PATTERN = re.compile(r"\\memcheck[A-Z]+\b")
MACRO_DEF_PATTERN = re.compile(r"\\newcommand\{(\\memcheck[A-Z]+)\}")
#: Comparative language that must be backed by a named statistical test.
SIGNIFICANCE_PATTERN = re.compile(
    r"\b(significantly|statistically significant|significant improvement)\b", re.IGNORECASE
)


@dataclass
class ValidationReport:
    checked_files: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    pending_markers: int = 0

    @property
    def ok(self) -> bool:
        return not self.errors

    def render(self) -> str:
        lines = [
            f"files checked      : {len(self.checked_files)}",
            f"errors             : {len(self.errors)}",
            f"warnings           : {len(self.warnings)}",
            f"[RESULT PENDING]   : {self.pending_markers} marker(s)",
        ]
        lines.extend(f"  error  : {message}" for message in self.errors)
        lines.extend(f"  warning: {message}" for message in self.warnings)
        if self.ok:
            lines.append("paper source validation passed")
        return "\n".join(lines)


def write_bibliography_block(paper_dir: Path) -> tuple[Path, int]:
    """Generate the bibliography block, which differs by whether any citation is verified yet.

    ``references.bib`` is empty by policy until a citation's metadata has been verified, and
    LaTeX refuses to typeset an empty ``thebibliography`` environment ("Something's wrong --
    perhaps a missing \\item"). Rather than smuggle in a placeholder entry — which is exactly
    the fabricated citation the policy forbids — the paper inputs a generated block that prints
    an honest note while the bibliography is empty and switches to the real one the moment an
    entry exists.
    """
    bib_path = paper_dir / "references.bib"
    entries = (
        len(BIB_ENTRY_PATTERN.findall(bib_path.read_text(encoding="utf-8")))
        if bib_path.exists()
        else 0
    )
    output = paper_dir / "generated" / "bibliography.tex"
    output.parent.mkdir(parents=True, exist_ok=True)
    if entries:
        output.write_text(
            "% Generated by memcheck. Do not edit by hand.\n"
            f"% references.bib defines {entries} verified entr"
            f"{'y' if entries == 1 else 'ies'}.\n"
            "\\bibliographystyle{IEEEtran}\n"
            "\\bibliography{references}\n",
            encoding="utf-8",
        )
    else:
        output.write_text(
            "% Generated by memcheck. Do not edit by hand.\n"
            "% references.bib is empty, so there is no bibliography to typeset. An entry is\n"
            "% added only after its metadata has been verified against the proceedings, the ACL\n"
            "% Anthology, arXiv, Crossref, the official repository, or the publisher's page.\n"
            "\\section*{References}\n"
            "\\textit{No references are listed. This artifact's policy is that a citation "
            "enters the bibliography only after its metadata has been verified against a "
            "primary source and the work has been read. The citations this draft intends to "
            "make are enumerated, with the claim each must support and where to verify it, in "
            "\\texttt{paper/references\\_todo.md}. No novelty claim in this draft should be "
            "accepted until that list has been worked through.}\n",
            encoding="utf-8",
        )
    return output, entries


def _resolve(base: Path, target: str) -> Path:
    path = base / target
    return path if path.suffix else path.with_suffix(".tex")


def validate_sources(paper_dir: Path) -> ValidationReport:
    """Validate the paper without a LaTeX engine."""
    report = ValidationReport()
    main = paper_dir / "main.tex"
    if not main.exists():
        report.errors.append(f"{main} does not exist")
        return report
    # Keep the generated bibliography block in step with references.bib before validating, so
    # validation sees exactly what a build would compile.
    _, entry_count = write_bibliography_block(paper_dir)
    if entry_count == 0:
        report.warnings.append(
            "references.bib defines no entries; the paper prints the no-references note. "
            "See paper/references_todo.md for the citations to verify."
        )

    # Walk \input/\include transitively so generated files are checked too.
    pending: list[Path] = [main]
    seen: set[Path] = set()
    documents: dict[Path, str] = {}
    while pending:
        current = pending.pop()
        if current in seen:
            continue
        seen.add(current)
        if not current.exists():
            report.errors.append(f"missing input: {current.relative_to(paper_dir)}")
            continue
        text = current.read_text(encoding="utf-8")
        documents[current] = text
        report.checked_files.append(str(current.relative_to(paper_dir)))
        for target in INPUT_PATTERN.findall(text):
            pending.append(_resolve(paper_dir, target))

    combined = "\n".join(documents.values())

    # Environments must balance, which is the most common hard compile failure.
    for path, text in documents.items():
        opened: list[str] = []
        tokens = sorted(
            [(match.start(), "begin", match.group(1)) for match in BEGIN_PATTERN.finditer(text)]
            + [(match.start(), "end", match.group(1)) for match in END_PATTERN.finditer(text)]
        )
        for _, kind, name in tokens:
            if kind == "begin":
                opened.append(name)
            elif not opened:
                report.errors.append(
                    f"{path.relative_to(paper_dir)}: \\end{{{name}}} with no matching \\begin"
                )
            elif opened[-1] != name:
                report.errors.append(
                    f"{path.relative_to(paper_dir)}: \\end{{{name}}} closes \\begin{{{opened[-1]}}}"
                )
                opened.pop()
            else:
                opened.pop()
        for name in opened:
            report.errors.append(
                f"{path.relative_to(paper_dir)}: \\begin{{{name}}} is never closed"
            )

    # Citations must exist in the bibliography. A fabricated citation key is the failure this
    # check exists to make impossible to miss.
    bib_path = paper_dir / "references.bib"
    defined_keys: set[str] = set()
    if bib_path.exists():
        defined_keys = set(BIB_ENTRY_PATTERN.findall(bib_path.read_text(encoding="utf-8")))
        report.checked_files.append("references.bib")
    else:
        report.errors.append("references.bib is missing")
    cited: set[str] = set()
    for group in CITE_PATTERN.findall(combined):
        cited.update(key.strip() for key in group.split(","))
    undefined = sorted(key for key in cited if key and key not in defined_keys)
    for key in undefined:
        report.errors.append(f"citation key {key!r} is used but not defined in references.bib")
    unused = sorted(key for key in defined_keys if key not in cited)
    for key in unused:
        report.warnings.append(f"bibliography entry {key!r} is defined but never cited")

    # Cross-references must resolve.
    labels = set(LABEL_PATTERN.findall(combined))
    for reference in sorted(set(REF_PATTERN.findall(combined))):
        for name in reference.split(","):
            if name.strip() and name.strip() not in labels:
                report.errors.append(f"reference to undefined label {name.strip()!r}")

    # Included graphics must exist.
    for target in GRAPHICS_PATTERN.findall(combined):
        # main.tex sets \graphicspath to generated/figures/, so a bare name resolves there.
        roots = (paper_dir, paper_dir / "generated" / "figures")
        candidates = [
            candidate
            for root in roots
            for candidate in (root / target, *(root / f"{target}{ext}" for ext in (".pdf", ".png")))
        ]
        if not any(candidate.exists() for candidate in candidates):
            report.warnings.append(
                f"figure {target!r} is included but has not been generated; run "
                "`memcheck report` first"
            )

    # A generated claim macro that the prose references but the registry never defined would be
    # an undefined control sequence: the build fails, and validation must catch it first.
    claims_path = paper_dir / "generated" / "claims.tex"
    defined_macros = (
        set(MACRO_DEF_PATTERN.findall(claims_path.read_text(encoding="utf-8")))
        if claims_path.exists()
        else set()
    )
    used_macros = set(MACRO_USE_PATTERN.findall(combined))
    for macro in sorted(used_macros - defined_macros):
        report.errors.append(
            f"claim macro {macro} is used in the text but no claim defines it; add the claim to "
            "claims_registry.yaml or fix the macro name, then re-run `memcheck report`"
        )
    for macro in sorted(defined_macros - used_macros):
        report.warnings.append(f"claim macro {macro} is defined but never used in the text")

    # Pending markers are expected while results are incomplete; they are counted, not an error.
    report.pending_markers = len(PENDING_PATTERN.findall(combined))

    # "Significantly" without a named test is exactly the overclaim the rules forbid.
    for path, text in documents.items():
        for match in SIGNIFICANCE_PATTERN.finditer(text):
            window = text[max(0, match.start() - 400) : match.end() + 400]
            preceding = text[max(0, match.start() - 120) : match.start()]
            # A sentence that explicitly *declines* to claim significance is the opposite of an
            # overclaim, so it must not be flagged as one.
            disclaimed = re.search(r"\b(do not|does not|never|without|no)\b", preceding, re.I)
            if disclaimed:
                continue
            if not re.search(r"Wilcoxon|Mann-Whitney|Holm|p\s*[=<]|Cliff", window, re.IGNORECASE):
                report.errors.append(
                    f"{path.relative_to(paper_dir)}: {match.group(0)!r} is used without a named "
                    "statistical test nearby"
                )

    return report


def build_pdf(paper_dir: Path, *, engine: str | None = None) -> tuple[bool, str]:
    """Compile the paper if a LaTeX engine exists; otherwise say so plainly."""
    from memcheck.utilities.environment import latex_engine

    write_bibliography_block(paper_dir)
    chosen = engine or latex_engine()
    if chosen is None:
        return False, (
            "no LaTeX engine found (looked for latexmk, pdflatex, tectonic, xelatex).\n"
            "Install one, or validate the source instead:\n"
            "  uv run memcheck paper --validate"
        )
    if chosen == "latexmk":
        command = [chosen, "-pdf", "-interaction=nonstopmode", "-halt-on-error", "main.tex"]
    elif chosen == "tectonic":
        # Tectonic runs the bibliography and reruns itself; it does not take pdflatex's flags.
        command = [chosen, "--keep-logs", "main.tex"]
    else:
        command = [chosen, "-interaction=nonstopmode", "-halt-on-error", "main.tex"]
    # A double-anonymous submission must not carry the author's timezone in its metadata, and a
    # fixed date makes the PDF reproducible. Both can be overridden from the environment.
    environment = {
        **os.environ,
        "TZ": os.environ.get("TZ", "UTC"),
        "SOURCE_DATE_EPOCH": os.environ.get("SOURCE_DATE_EPOCH", ANONYMOUS_SOURCE_DATE_EPOCH),
    }
    completed = subprocess.run(
        command,
        cwd=paper_dir,
        capture_output=True,
        text=True,
        check=False,
        timeout=600,
        env=environment,
    )
    if completed.returncode != 0:
        tail = "\n".join(completed.stdout.splitlines()[-40:])
        return False, f"{chosen} failed with code {completed.returncode}:\n{tail}"
    return True, f"{chosen} produced {paper_dir / 'main.pdf'}"
